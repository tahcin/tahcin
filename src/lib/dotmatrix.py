def text_width(text, pitch):
    """Width in user units of `text` when each pin is `pitch` apart."""
    return (len(text) * 6 - 1) * pitch


def columns(text):
    """Yield (column_index, [row indices with a pin]) across the whole string."""
    col = 0
    for ch in text:
        g = GLYPHS.get(ch) or GLYPHS.get(ch.upper()) or GLYPHS["?"]
        for c in range(5):
            rows = [r for r in range(7) if g[r][c] == "#"]
            yield col, rows
            col += 1
        yield col, []  # inter-character gap
        col += 1


def render(text, x, y, pitch=4.0, r=None, fill="currentColor", cls=None,
           per_column=False):
    """Render dot-matrix text with top-left at (x, y).

    per_column=True wraps every printed column in its own <g data-c="n">
    so callers can stagger an animation per column (printhead strike).
    """
    r = r if r is not None else pitch * 0.42
    out = []
    cls_attr = f' class="{cls}"' if cls else ""
    for col, rows in columns(text):
        if not rows:
            continue
        cx = x + col * pitch + pitch / 2
        dots = "".join(
            f'<circle cx="{cx:.2f}" cy="{y + rr * pitch + pitch / 2:.2f}" r="{r:.2f}"/>'
            for rr in rows
        )
        if per_column:
            out.append((col, dots))
        else:
            out.append(dots)
    if per_column:
        return out
    return f'<g fill="{fill}"{cls_attr}>{"".join(out)}</g>'


def path_d(text, x, y, pitch=4.0, size=None):
    """Same glyphs as square pins in a single compact path (cheap in bytes)."""
    s = size if size is not None else pitch * 0.8
    off = (pitch - s) / 2
    parts = []
    for col, rows in columns(text):
        for rr in rows:
            px = x + col * pitch + off
            py = y + rr * pitch + off
            parts.append(f"M{px:.1f} {py:.1f}h{s:.1f}v{s:.1f}h-{s:.1f}z")
    return "".join(parts)
